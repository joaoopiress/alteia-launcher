// Converte cada linha da grelha em retângulos horizontais contíguos.
const RECTS = Object.fromEntries(
  Object.entries(GRIDS).map(([name, rows]) => {
    const rects = [];
    rows.forEach((row, y) => {
      let x = 0;
      while (x < row.length) {
        if (row[x] !== '#') {
          x++;
          continue;
        }
        const start = x;
        while (row[x] === '#') x++;
        rects.push([start, y, x - start]);
      }
    });
    return [name, rects];
  })
);

export default function Icon({ name, size = 18, className = '' }) {
  const rects = RECTS[name] || [];
  return (
    <svg
      className={`icon ${className}`}
      width={size}
      height={size}
      viewBox="0 0 9 9"
      fill="currentColor"
      shapeRendering="crispEdges"
      aria-hidden="true"
    >
      {rects.map(([x, y, w]) => (
        <rect key={`${x}-${y}`} x={x} y={y} width={w} height={1} />
      ))}
    </svg>
  );
}
