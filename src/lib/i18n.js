const DICTS = { pt, en };
export const LANGUAGES = [
  { id: 'pt', label: 'Português (PT)' },
  { id: 'en', label: 'English' },
];

let lang = 'pt';

export function setLang(value) {
  lang = DICTS[value] ? value : 'pt';
}

export function getLang() {
  return lang;
}

// Locale usado nas datas e números.
export function locale() {
  return lang === 'en' ? 'en-GB' : 'pt-PT';
}

export function t(key, vars) {
  let s = DICTS[lang][key] ?? pt[key] ?? key;
  if (vars) s = s.replace(/\{(\w+)\}/g, (_, k) => (vars[k] ?? '').toString());
  return s;
}

// Plural simples: chave.one para 1, chave.other para os restantes.
export function tn(key, n, vars = {}) {
  return t(`${key}.${n === 1 ? 'one' : 'other'}`, { n, ...vars });
}

export function list(key) {
  return t(key).split(',');
}
